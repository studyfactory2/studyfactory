/**
 * Exercises the deployment SQL and its PostgreSQL-only audit trigger, not an H2 approximation.
 * Supply a disposable loopback database ending in {@code _test}; each test owns a separate schema.
 */
@EnabledIfEnvironmentVariable(named = "BEVERAGE_TEST_JDBC_URL", matches = ".+")
@DisplayName("PostgreSQL 음료 배포 마이그레이션 보존 테스트")
class BeverageAuditMigrationPostgresTest {

    private static final Path MIGRATION =
            Path.of("db/migrations/20260909_01_beverage_preference_audits.sql");
    private static final List<String> BEVERAGE_TABLES = List.of(
            "beverage_items",
            "beverage_preferences",
            "beverage_preference_items",
            "beverage_preference_drink_notes"
    );

    private Connection connection;
    private String schema;
    private boolean schemaCreated;

    @BeforeEach
    void setUp() throws SQLException {
        String jdbcUrl = System.getenv("BEVERAGE_TEST_JDBC_URL");
        requireDisposableLocalDatabase(jdbcUrl);
        connection = DriverManager.getConnection(
                jdbcUrl,
                System.getenv().getOrDefault("BEVERAGE_TEST_DB_USER", "postgres"),
                System.getenv().getOrDefault("BEVERAGE_TEST_DB_PASSWORD", "")
        );
        schema = "beverage_audit_test_" + UUID.randomUUID().toString().replace("-", "");
        execute("CREATE SCHEMA " + schema);
        schemaCreated = true;
        execute("SET search_path TO " + schema);
        execute("SET TIME ZONE 'UTC'");
        execute("""
                CREATE TABLE members (id bigint PRIMARY KEY);
                CREATE TABLE beverage_items (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    member_id bigint NOT NULL,
                    name varchar(255) NOT NULL,
                    note text,
                    created_at timestamp(6) NOT NULL,
                    updated_at timestamp(6) NOT NULL
                );
                CREATE TABLE beverage_preferences (
                    id bigint PRIMARY KEY,
                    member_id bigint NOT NULL,
                    drinks text,
                    notes text,
                    created_at timestamp(6) NOT NULL,
                    updated_at timestamp(6) NOT NULL
                );
                CREATE TABLE beverage_preference_items (
                    id bigint PRIMARY KEY,
                    beverage_preference_id bigint NOT NULL,
                    name varchar(255) NOT NULL,
                    note text
                );
                CREATE TABLE beverage_preference_drink_notes (
                    beverage_preference_id bigint NOT NULL,
                    drink_name varchar(255) NOT NULL,
                    note text,
                    PRIMARY KEY (beverage_preference_id, drink_name)
                );
                """);
    }

    @AfterEach
    void tearDown() throws SQLException {
        if (connection == null) {
            return;
        }
        try {
            // A failing migration may leave its explicit transaction aborted.
            execute("ROLLBACK");
            if (schemaCreated) {
                execute("SET search_path TO pg_catalog");
                execute("DROP SCHEMA " + schema + " CASCADE");
            }
        } finally {
            connection.close();
        }
    }

    @Test
    @DisplayName("반복 배포는 현재 음료·메모·중복 수량·빈 설정과 기존 변경 시간을 그대로 보존한다")
    void repeatedMigrationPreservesCurrentItemsArchivesAndAuthoritativeAudits() throws Exception {
        execute("""
                INSERT INTO members VALUES (1), (2), (3), (4), (5);
                INSERT INTO beverage_items
                    (id, member_id, name, note, created_at, updated_at) VALUES
                    (101, 1, '선식반컵', '현재 설정', '2026-10-22 08:00:00', '2026-10-22 08:00:00'),
                    (201, 2, '물', NULL, '2026-10-22 08:01:00', '2026-10-22 08:01:00'),
                    (401, 4, '아아', '연하게', '2026-10-22 08:02:00', '2026-10-22 08:02:00'),
                    (402, 4, '아아', '얼음 적게', '2026-10-22 08:03:00', '2026-10-22 08:03:00'),
                    (501, 5, '해독', '그대로 유지', '2026-10-22 08:04:00', '2026-10-22 08:04:00');
                INSERT INTO beverage_preferences VALUES
                    (10, 1, '선식', '예전 한 컵', '2000-01-01', '2099-01-01'),
                    (20, 2, '아아,물', '삭제한 아아', '2000-01-01', '2099-01-01'),
                    (30, 3, '아아', '모두 삭제함', '2000-01-01', '2099-01-01'),
                    (40, 4, '아아', '예전 메모', '2000-01-01', '2099-01-01'),
                    (50, 5, '해독쥬스', '예전 표기', '2000-01-01', '2099-01-01');
                INSERT INTO beverage_preference_items VALUES
                    (11, 10, '선식', '예전 한 컵'),
                    (21, 20, '아아', '삭제한 아아'),
                    (31, 30, '아아', '모두 삭제함');
                INSERT INTO beverage_preference_drink_notes VALUES
                    (10, '선식', '예전 메모'), (30, '아아', '삭제한 메모');
                CREATE TABLE beverage_preference_audits (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    member_id bigint NOT NULL,
                    created_at timestamp(6) with time zone NOT NULL,
                    updated_at timestamp(6) with time zone NOT NULL
                );
                INSERT INTO beverage_preference_audits (member_id, created_at, updated_at)
                    SELECT id, TIMESTAMPTZ '2026-10-01 03:00:00+00',
                        TIMESTAMPTZ '2026-10-21 04:00:00+00' FROM members;
                """);
        Map<String, List<List<String>>> drinksBefore = snapshotBeverageTables();
        List<List<String>> auditsBefore = rows("SELECT * FROM beverage_preference_audits ORDER BY id");

        applyMigration();
        applyMigration();

        assertThat(snapshotBeverageTables()).isEqualTo(drinksBefore);
        assertThat(rows("SELECT * FROM beverage_preference_audits ORDER BY id")).isEqualTo(auditsBefore);
        assertThat(rows("SELECT name FROM beverage_items WHERE member_id = 1 ORDER BY id"))
                .containsExactly(List.of("선식반컵"));
        assertThat(rows("SELECT name FROM beverage_items WHERE member_id = 2 ORDER BY id"))
                .containsExactly(List.of("물"));
        assertThat(rows("SELECT name FROM beverage_items WHERE member_id = 3")).isEmpty();
        assertThat(rows("SELECT name FROM beverage_items WHERE member_id = 4 ORDER BY id"))
                .containsExactly(List.of("아아"), List.of("아아"));
    }

    @Test
    @DisplayName("누락된 변경 이력만 현재 음료에서 보완하고 옛 설정만 남은 회원의 활동은 만들지 않는다")
    void backfillsMissingAuditsOnlyFromCurrentItemsAndNeverFromLegacyPreferences() throws Exception {
        execute("""
                INSERT INTO members VALUES (1), (2), (3);
                INSERT INTO beverage_items
                    (id, member_id, name, note, created_at, updated_at) VALUES
                    (101, 1, '선식반컵', '현재 설정', '2026-10-01 01:00:00', '2026-10-20 02:00:00'),
                    (102, 1, '물', NULL, '2026-10-02 01:00:00', '2026-10-21 03:00:00');
                INSERT INTO beverage_preferences VALUES
                    (10, 1, '선식', '옛 설정', '2000-01-01', '2099-01-01'),
                    (20, 2, '아아', '현재는 신청 없음', '2000-01-01', '2099-01-01'),
                    (90, 99, '선식', '이미 삭제한 회원', '2000-01-01', '2099-01-01');
                INSERT INTO beverage_preference_items VALUES (21, 20, '아아', '옛 설정');
                """);
        Map<String, List<List<String>>> drinksBefore = snapshotBeverageTables();

        applyMigration();
        Audit first = auditFor(1);
        List<List<String>> firstAudits = rows("SELECT * FROM beverage_preference_audits ORDER BY id");
        applyMigration();

        assertThat(first.createdAt()).isEqualTo(Instant.parse("2026-10-01T01:00:00Z"));
        assertThat(first.updatedAt()).isEqualTo(Instant.parse("2026-10-21T03:00:00Z"));
        assertThat(rows("SELECT member_id FROM beverage_preference_audits ORDER BY member_id"))
                .containsExactly(List.of("1"));
        assertThat(rows("SELECT * FROM beverage_preference_audits ORDER BY id")).isEqualTo(firstAudits);
        assertThat(snapshotBeverageTables()).isEqualTo(drinksBefore);
    }

    @Test
    @DisplayName("실제 추가·삭제는 변경 이력을 갱신하고 모두 삭제 후 재배포와 재신청에도 시작 이력을 유지한다")
    void realItemWritesStillUpdateAuditIncludingDeleteToEmptyAndRecreation() throws Exception {
        execute("""
                INSERT INTO members VALUES (1);
                INSERT INTO beverage_items
                    (member_id, name, note, created_at, updated_at) VALUES
                    (1, '선식', '기존 요청', '2000-01-01', '2000-01-01');
                INSERT INTO beverage_preferences VALUES
                    (10, 1, '선식', '복구하면 안 되는 옛 설정', '1990-01-01', '2099-01-01');
                """);
        applyMigration();
        Audit original = auditFor(1);

        execute("""
                INSERT INTO beverage_items (member_id, name, note, created_at, updated_at)
                VALUES (1, '선식반컵', '새 요청', CURRENT_TIMESTAMP, CURRENT_TIMESTAMP);
                """);
        Audit added = auditFor(1);
        assertThat(added.createdAt()).isEqualTo(original.createdAt());
        assertThat(added.updatedAt()).isAfter(original.updatedAt());

        execute("SELECT pg_sleep(0.002)");
        execute("DELETE FROM beverage_items WHERE member_id = 1");
        Audit deleted = auditFor(1);
        assertThat(deleted.id()).isEqualTo(original.id());
        assertThat(deleted.createdAt()).isEqualTo(original.createdAt());
        assertThat(deleted.updatedAt()).isAfter(added.updatedAt());
        assertThat(rows("SELECT * FROM beverage_items")).isEmpty();

        applyMigration();
        applyMigration();
        assertThat(auditFor(1)).isEqualTo(deleted);
        assertThat(rows("SELECT * FROM beverage_items")).isEmpty();

        execute("""
                INSERT INTO beverage_items (member_id, name, note, created_at, updated_at)
                VALUES (1, '물', '직접 다시 신청', CURRENT_TIMESTAMP, CURRENT_TIMESTAMP);
                """);
        Audit recreated = auditFor(1);
        assertThat(recreated.id()).isEqualTo(original.id());
        assertThat(recreated.createdAt()).isEqualTo(original.createdAt());
        assertThat(recreated.updatedAt()).isAfter(deleted.updatedAt());
        assertThat(rows("SELECT name FROM beverage_items ORDER BY id")).containsExactly(List.of("물"));
    }

    private void applyMigration() throws Exception {
        execute(Files.readString(MIGRATION));
    }

    private void execute(String sql) throws SQLException {
        try (Statement statement = connection.createStatement()) {
            statement.execute(sql);
        }
    }

    private Map<String, List<List<String>>> snapshotBeverageTables() throws SQLException {
        Map<String, List<List<String>>> snapshot = new LinkedHashMap<>();
        for (String table : BEVERAGE_TABLES) {
            String order = table.equals("beverage_preference_drink_notes")
                    ? "beverage_preference_id, drink_name"
                    : "id";
            snapshot.put(table, rows("SELECT * FROM " + table + " ORDER BY " + order));
        }
        return snapshot;
    }

    private List<List<String>> rows(String sql) throws SQLException {
        List<List<String>> result = new ArrayList<>();
        try (Statement statement = connection.createStatement(); ResultSet rows = statement.executeQuery(sql)) {
            int columns = rows.getMetaData().getColumnCount();
            while (rows.next()) {
                List<String> row = new ArrayList<>();
                for (int column = 1; column <= columns; column++) {
                    row.add(rows.getString(column));
                }
                result.add(row);
            }
        }
        return result;
    }

    private Audit auditFor(long memberId) throws SQLException {
        try (var statement = connection.prepareStatement("""
                SELECT id, created_at, updated_at FROM beverage_preference_audits WHERE member_id = ?
                """)) {
            statement.setLong(1, memberId);
            try (ResultSet row = statement.executeQuery()) {
                assertThat(row.next()).as("audit for member %s", memberId).isTrue();
                Audit audit = new Audit(
                        row.getLong("id"),
                        row.getObject("created_at", OffsetDateTime.class).toInstant(),
                        row.getObject("updated_at", OffsetDateTime.class).toInstant()
                );
                assertThat(row.next()).isFalse();
                return audit;
            }
        }
    }

    private static void requireDisposableLocalDatabase(String jdbcUrl) {
        if (jdbcUrl == null || !jdbcUrl.startsWith("jdbc:postgresql://")) {
            throw new IllegalArgumentException("Beverage migration tests require a loopback PostgreSQL test database.");
        }
        URI uri = URI.create(jdbcUrl.substring("jdbc:".length()));
        String databasePath = uri.getPath();
        if (uri.getHost() == null
                || !Set.of("localhost", "127.0.0.1", "[::1]", "::1").contains(uri.getHost())
                || uri.getUserInfo() != null || uri.getQuery() != null || uri.getFragment() != null
                || databasePath == null || !databasePath.matches("/[a-zA-Z0-9_]+_test")) {
            throw new IllegalArgumentException(
                    "Use a loopback PostgreSQL URL with a database ending in _test and no URL options."
            );
        }
    }

    private record Audit(long id, Instant createdAt, Instant updatedAt) {
    }
}
