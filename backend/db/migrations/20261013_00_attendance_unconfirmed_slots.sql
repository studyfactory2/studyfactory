-- Explicitly unconfirmed cells are separate from attendance and leave records.
-- Older backend images ignore this table; they never count these rows as O.
-- Rollback can expose preserved leave again, so deploy the backend before UI use.

BEGIN;

CREATE TABLE IF NOT EXISTS attendance_unconfirmed_slots (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id bigint NOT NULL,
    branch_id bigint NOT NULL,
    attendance_date date NOT NULL,
    slot integer NOT NULL,
    cleared_by_member_id bigint,
    cleared_at timestamp(6) with time zone NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_attendance_unconfirmed_slots_member_date_slot
    ON attendance_unconfirmed_slots (member_id, attendance_date, slot);

CREATE INDEX IF NOT EXISTS idx_attendance_unconfirmed_slots_branch_date
    ON attendance_unconfirmed_slots (branch_id, attendance_date);

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'ck_attendance_unconfirmed_slots_slot'
          AND conrelid = 'attendance_unconfirmed_slots'::regclass
    ) THEN
        ALTER TABLE attendance_unconfirmed_slots
            ADD CONSTRAINT ck_attendance_unconfirmed_slots_slot CHECK (slot BETWEEN 1 AND 7);
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_attendance_unconfirmed_slots_member'
          AND conrelid = 'attendance_unconfirmed_slots'::regclass
    ) THEN
        ALTER TABLE attendance_unconfirmed_slots
            ADD CONSTRAINT fk_attendance_unconfirmed_slots_member
            FOREIGN KEY (member_id) REFERENCES members (id) ON DELETE CASCADE;
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_attendance_unconfirmed_slots_operator'
          AND conrelid = 'attendance_unconfirmed_slots'::regclass
    ) THEN
        ALTER TABLE attendance_unconfirmed_slots
            ADD CONSTRAINT fk_attendance_unconfirmed_slots_operator
            FOREIGN KEY (cleared_by_member_id) REFERENCES members (id) ON DELETE SET NULL;
    END IF;
END $$;

COMMIT;
