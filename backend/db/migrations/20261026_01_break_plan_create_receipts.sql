-- Additive retry receipts only. Lunch/dinner plans continue to use weekly_plan_items.
-- No foreign key to item_id: a retry must not recreate an explicitly deleted item.
BEGIN;

CREATE TABLE IF NOT EXISTS break_plan_create_receipts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id bigint NOT NULL,
    week_start_date date NOT NULL,
    client_request_id uuid NOT NULL,
    create_fingerprint varchar(64) NOT NULL,
    item_id bigint NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL
);

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'ck_break_plan_create_receipts_fingerprint'
          AND conrelid = 'break_plan_create_receipts'::regclass
    ) THEN
        ALTER TABLE break_plan_create_receipts
            ADD CONSTRAINT ck_break_plan_create_receipts_fingerprint CHECK (char_length(create_fingerprint) = 64);
    END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS uk_break_plan_create_receipts_member_request
    ON break_plan_create_receipts (member_id, client_request_id);

CREATE INDEX IF NOT EXISTS idx_break_plan_create_receipts_member_week
    ON break_plan_create_receipts (member_id, week_start_date);

COMMIT;
