-- Additive storage only: existing weekly_plan_items and goals are not changed.
-- A week becomes protected from legacy whole-week replacement only after a
-- successful shared-checklist mutation. Reading a week does not activate it.
BEGIN;

CREATE TABLE IF NOT EXISTS shared_plan_weeks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id bigint NOT NULL,
    week_start_date date NOT NULL,
    revision bigint NOT NULL DEFAULT 0,
    legacy_save_protected boolean NOT NULL DEFAULT false,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL
);

CREATE TABLE IF NOT EXISTS shared_plan_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id bigint NOT NULL,
    branch_id bigint NOT NULL,
    week_start_date date NOT NULL,
    day_index integer NOT NULL,
    plan_group varchar(30) NOT NULL,
    content text NOT NULL,
    done boolean NOT NULL DEFAULT false,
    sort_order integer NOT NULL,
    client_request_id uuid NOT NULL,
    create_fingerprint varchar(64) NOT NULL,
    deleted boolean NOT NULL DEFAULT false,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL
);

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'ck_shared_plan_weeks_revision'
          AND conrelid = 'shared_plan_weeks'::regclass
    ) THEN
        ALTER TABLE shared_plan_weeks
            ADD CONSTRAINT ck_shared_plan_weeks_revision CHECK (revision >= 0);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'ck_shared_plan_items_day'
          AND conrelid = 'shared_plan_items'::regclass
    ) THEN
        ALTER TABLE shared_plan_items
            ADD CONSTRAINT ck_shared_plan_items_day CHECK (day_index between 0 and 6);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'ck_shared_plan_items_sort_order'
          AND conrelid = 'shared_plan_items'::regclass
    ) THEN
        ALTER TABLE shared_plan_items
            ADD CONSTRAINT ck_shared_plan_items_sort_order CHECK (sort_order >= 0);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'ck_shared_plan_items_group'
          AND conrelid = 'shared_plan_items'::regclass
    ) THEN
        ALTER TABLE shared_plan_items
            ADD CONSTRAINT ck_shared_plan_items_group CHECK (
                plan_group in ('PERIODS_1_2', 'PERIODS_3_5', 'PERIODS_6_7')
            );
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'ck_shared_plan_items_fingerprint'
          AND conrelid = 'shared_plan_items'::regclass
    ) THEN
        ALTER TABLE shared_plan_items
            ADD CONSTRAINT ck_shared_plan_items_fingerprint CHECK (char_length(create_fingerprint) = 64);
    END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS uk_shared_plan_weeks_member_week
    ON shared_plan_weeks (member_id, week_start_date);

CREATE UNIQUE INDEX IF NOT EXISTS uk_shared_plan_items_member_request
    ON shared_plan_items (member_id, client_request_id);

CREATE INDEX IF NOT EXISTS idx_shared_plan_items_member_week_order
    ON shared_plan_items (member_id, week_start_date, day_index, sort_order, id);

COMMIT;
