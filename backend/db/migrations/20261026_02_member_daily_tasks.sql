-- Additive member-owned daily tasks only. Existing plans, staff/admin todos,
-- attendance, and study records are unchanged; no backfill or activation occurs.
-- Deleted items retain their create-request receipt to make retries duplicate-safe.
BEGIN;

CREATE TABLE IF NOT EXISTS member_task_days (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id bigint NOT NULL,
    task_date date NOT NULL,
    revision bigint NOT NULL DEFAULT 0,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL
);

CREATE TABLE IF NOT EXISTS member_task_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id bigint NOT NULL,
    task_date date NOT NULL,
    content text NOT NULL,
    completed boolean NOT NULL DEFAULT false,
    sort_order integer NOT NULL,
    client_request_id uuid NOT NULL,
    create_fingerprint varchar(64) NOT NULL,
    deleted boolean NOT NULL DEFAULT false,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL
);

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'ck_member_task_days_revision'
          AND conrelid = 'member_task_days'::regclass
    ) THEN
        ALTER TABLE member_task_days
            ADD CONSTRAINT ck_member_task_days_revision CHECK (revision >= 0);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'ck_member_task_items_sort_order'
          AND conrelid = 'member_task_items'::regclass
    ) THEN
        ALTER TABLE member_task_items
            ADD CONSTRAINT ck_member_task_items_sort_order CHECK (sort_order >= 0);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'ck_member_task_items_fingerprint'
          AND conrelid = 'member_task_items'::regclass
    ) THEN
        ALTER TABLE member_task_items
            ADD CONSTRAINT ck_member_task_items_fingerprint CHECK (char_length(create_fingerprint) = 64);
    END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS uk_member_task_days_member_date
    ON member_task_days (member_id, task_date);

CREATE UNIQUE INDEX IF NOT EXISTS uk_member_task_items_member_request
    ON member_task_items (member_id, client_request_id);

CREATE INDEX IF NOT EXISTS idx_member_task_items_member_date_order
    ON member_task_items (member_id, task_date, sort_order, id);

COMMIT;
